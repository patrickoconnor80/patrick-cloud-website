#!/usr/bin/env python3
"""Build src/assets/js/mktcap-data.js for the price-vs-market-cap charts on the stock pages.

Daily closes come from Yahoo Finance's chart endpoint; share counts come from the cover page of
each 10-Q/10-K (SEC XBRL "dei:EntityCommonStockSharesOutstanding"). The chart multiplies price by
a share count interpolated between those filing dates, so the gap between the two lines is
dilution. Counts newer than the last filing are added by hand in EXTRA below.

    SEC_USER_AGENT="Your Name you@example.com" python3 bin/build_mktcap.py

SEC asks for a contact in the User-Agent; set it in your environment rather than committing it.
To add a ticker, add an entry to TICKERS (CIK is on the company's EDGAR page).
"""
import datetime, json, os, sys, urllib.request

TICKERS = {
    "IONQ": {
        "cik": "0001824920",
        "extra": [
            ["2026-10-13", 408907678, "Oct 13, 2026 count from the Oct 14 offering prospectus supplement (via securities.io)"],
        ],
    },
    "ONDS": {
        "cik": "0001646188",
        "extra": [
            ["2026-09-22", 582300000, "Sept 22, 2026 count of 582.3M, as cited on the ONDS page"],
        ],
    },
}
RANGE = "2y"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "assets", "js", "mktcap-data.js")


def get(url, ua):
    req = urllib.request.Request(url, headers={"User-Agent": ua})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def prices(ticker):
    d = get(f"https://query1.finance.yahoo.com/v8/finance/chart/{ticker}?range={RANGE}&interval=1d", "Mozilla/5.0")
    res = d["chart"]["result"][0]
    out = []
    for ts, c in zip(res["timestamp"], res["indicators"]["quote"][0]["close"]):
        if c is None:
            continue
        day = datetime.datetime.fromtimestamp(ts, datetime.timezone.utc).strftime("%Y-%m-%d")
        out.append([day, round(c, 3)])
    return out


def shares(cik, ua, since):
    facts = get(f"https://data.sec.gov/api/xbrl/companyfacts/CIK{cik}.json", ua)
    rows = facts["facts"]["dei"]["EntityCommonStockSharesOutstanding"]["units"]["shares"]
    latest = {}
    for r in rows:
        if r["end"] not in latest or r["filed"] > latest[r["end"]]["filed"]:
            latest[r["end"]] = r
    out = [[e, r["val"], r["form"]] for e, r in sorted(latest.items())]
    keep_from = (datetime.date.fromisoformat(since) - datetime.timedelta(days=150)).isoformat()
    return [x for x in out if x[0] >= keep_from]


def main():
    ua = os.environ.get("SEC_USER_AGENT")
    if not ua:
        sys.exit('Set SEC_USER_AGENT="Your Name you@example.com" (SEC requires a contact).')
    data = {"updated": datetime.date.today().isoformat()}
    for t, cfg in TICKERS.items():
        p = prices(t)
        s = shares(cfg["cik"], ua, p[0][0])
        for day, val, note in cfg["extra"]:
            if not any(x[0] == day for x in s):
                s.append([day, val, note])
        s.sort(key=lambda x: x[0])
        data[t] = {"prices": p, "shares": s}
        print(f"{t}: {len(p)} prices {p[0][0]}..{p[-1][0]}, {len(s)} share counts, latest {s[-1][0]} = {s[-1][1]:,}")
    with open(OUT, "w") as f:
        f.write("// Generated by bin/build_mktcap.py. Do not edit by hand.\n")
        f.write("window.MKTCAP = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
